#!/usr/bin/env python3
"""Compile src/gfx/shaders/*.vert|*.frag to SPIR-V and embed them in
src/gfx/shaders_spv.h, which is committed so nobody else needs a shader
compiler. Needs glslangValidator (package glslang-tools)."""
import os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "gfx", "shaders")
OUT = os.path.join(ROOT, "src", "gfx", "shaders_spv.h")

def main():
    lines = ["/* Generated by tools/compile_shaders.py from src/gfx/shaders. Do not edit. */",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]
    for name in sorted(os.listdir(SRC)):
        if not name.endswith((".vert", ".frag")):
            continue
        with tempfile.TemporaryDirectory() as tmp:
            spv = os.path.join(tmp, "out.spv")
            subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.0",
                            "-o", spv, os.path.join(SRC, name)], check=True,
                           stdout=subprocess.DEVNULL)
            data = open(spv, "rb").read()
        ident = name.replace(".", "_")
        lines.append(f"static const uint8_t {ident}_spv[{len(data)}] = {{")
        for i in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    open(OUT, "w").write("\n".join(lines))
    print("wrote", OUT)

if __name__ == "__main__":
    sys.exit(main())
